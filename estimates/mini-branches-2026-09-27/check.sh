#!/usr/bin/env bash
# Read-only inventory comparison and stratified ROOT schema sampling on IHEP.
set -eo pipefail
source /cvmfs/sft.cern.ch/lcg/views/LCG_110/x86_64-el9-gcc13-opt/setup.sh
set -u
python3 -u - <<'PY'
import collections
import datetime
import hashlib
import json
import os
from pathlib import Path
import socket
import time

import ROOT
ROOT.PyConfig.DisableRootLogon = True
ROOT.gROOT.SetBatch(True)

BASE = Path('/lustrefs/juno26/dyw/rec/All-mini')
LISTS = BASE.parent / 'list'
CATALOGS = Path('/dybfs2/users/lijj16/DYB_DATA_PRESERVATION/code/catalog_backups')
MANIFEST_SHA = 'f7e87d4884118170f27c6dff1b64a34cd783d88f5490bc952334430058067728'
REQUIRED = {
    'Event/Rec/AdSimpleNL': {
        'site': 'Short_t', 'detector': 'Short_t', 'triggerType': 'UInt_t',
        'triggerNumber': 'UInt_t', 'triggerTimeSec': 'Int_t',
        'triggerTimeNanoSec': 'Int_t', 'energy': 'Float_t',
        'x': 'Float_t', 'y': 'Float_t', 'z': 'Float_t',
    },
    'Event/Data/CalibStats': {
        'nHit': 'Int_t', 'MiddleTimeRMS': 'Float_t', 'Quadrant': 'Float_t',
        'Q1': 'Float_t', 'Q2': 'Float_t', 'MaxQ': 'Float_t',
        'MaxQ_2inchPMT': 'Float_t', 'Kurtosis': 'Float_t',
        'time_PSD_local_RMS': 'Float_t',
    },
}

def emit(kind, **values):
    print(json.dumps(dict(kind=kind, **values), sort_keys=True), flush=True)

started = time.monotonic()
emit('environment', utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),
     host=socket.gethostname(), root_version=ROOT.gROOT.GetVersion(), required=REQUIRED,
     note='runNumber and Preservation metadata are generated by our converter')
manifest = (CATALOGS / 'SHA256SUMS').read_bytes()
assert hashlib.sha256(manifest).hexdigest() == MANIFEST_SHA
groups = collections.defaultdict(lambda: collections.defaultdict(list))
expected = set()
catalog_errors = []
catalog_count = 0
for line in manifest.decode().splitlines():
    digest, relative = line.split()
    try:
        data = (CATALOGS / relative).read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError('catalog SHA256 mismatch')
        period, hall, catalog = relative.split('/')
        for source in data.decode().splitlines():
            source_path = Path(source)
            mini = BASE / source_path.relative_to('/dybfs/rec/' + period + '/rec')
            mini = str(mini.with_name('mini' + source_path.name))
            if mini in expected:
                raise ValueError('duplicate source: ' + source)
            expected.add(mini)
            tag = source_path.name.split('.')[1]
            groups[(period, hall, tag)][catalog].append((mini, source))
        catalog_count += 1
    except (OSError, ValueError) as exc:
        catalog_errors.append({'catalog': relative, 'error': str(exc)})
emit('catalogs', read=catalog_count, expected_files=len(expected), errors=catalog_errors,
     checksum_manifest_sha256=MANIFEST_SHA)
if catalog_errors or catalog_count != 4009 or len(expected) != 831334:
    raise RuntimeError('cannot compare an incomplete fixed catalog snapshot')

indexes = {}
for name in ('file_list.txt', 'file_lost.txt'):
    data = (LISTS / name).read_bytes()
    lines = [line for line in data.decode().splitlines() if line]
    indexes[name] = set(lines)
    emit('index', path=str(LISTS / name), bytes=len(data), lines=len(lines),
         duplicate_lines=len(lines) - len(indexes[name]),
         sha256=hashlib.sha256(data).hexdigest(),
         mtime_utc=datetime.datetime.fromtimestamp((LISTS / name).stat().st_mtime,
                                                  datetime.timezone.utc).isoformat())
listed = indexes['file_list.txt']
lost = indexes['file_lost.txt']
emit('coverage', expected=len(expected), in_file_list=len(expected & listed),
     absent_from_file_list=len(expected - listed), in_file_lost=len(expected & lost),
     listed_as_both=len(expected & listed & lost),
     extra_listed=len(listed - expected),
     note='Inventory comparison only; not a fresh stat or ROOT read of every archive file')

samples = []
for (period, hall, tag), runs in sorted(groups.items()):
    group_paths = {pair[0] for run in runs.values() for pair in run}
    emit('group_coverage', period=period, hall=hall, tag=tag, runs=len(runs),
         expected=len(group_paths), in_file_list=len(group_paths & listed),
         in_file_lost=len(group_paths & lost),
         absent_from_file_list=len(group_paths - listed))
    eligible_runs = sorted(run for run in runs if any(pair[0] in listed for pair in runs[run]))
    if not eligible_runs:
        continue
    # Three run quantiles in every period, hall, and stream that exists.
    for index in sorted({min(len(eligible_runs) - 1, len(eligible_runs) * q // 6)
                         for q in (1, 3, 5)}):
        run = eligible_runs[index]
        candidates = sorted(pair for pair in runs[run] if pair[0] in listed)
        mini, source = candidates[len(candidates) // 2]
        samples.append((period, hall, tag, mini, source))

passed = 0
for period, hall, tag, mini, source in samples:
    record = dict(period=period, hall=hall, tag=tag, path=mini, source=source,
                  trees={}, errors=[])
    f = None
    try:
        f = ROOT.TFile.Open(mini, 'READ')
        if not f or f.IsZombie():
            raise RuntimeError('cannot open ROOT file')
        for tree_path, required in REQUIRED.items():
            tree = f.Get(tree_path)
            if not tree or not tree.InheritsFrom('TTree'):
                record['errors'].append('missing tree ' + tree_path)
                continue
            leaves = {leaf.GetName(): leaf.GetTypeName() for leaf in tree.GetListOfLeaves()}
            branches = [branch.GetName() for branch in tree.GetListOfBranches()]
            missing = [name for name in required if not tree.GetBranch(name)]
            wrong_types = {name: leaves.get(name) for name, dtype in required.items()
                           if leaves.get(name) != dtype}
            entries = tree.GetEntries()
            info = dict(entries=entries, branches=branches, leaves=leaves,
                        missing=missing, wrong_types=wrong_types, entry_reads=[])
            record['trees'][tree_path] = info
            if missing or wrong_types or entries <= 0:
                record['errors'].append('invalid required schema/count in ' + tree_path)
                continue
            tree.SetBranchStatus('*', False)
            for name in required:
                tree.SetBranchStatus(name, True)
            for entry in sorted({0, entries // 2, entries - 1}):
                count = tree.GetEntry(entry)
                info['entry_reads'].append({'entry': entry, 'bytes': count})
                if count <= 0:
                    record['errors'].append('cannot read entry in ' + tree_path)
        counts = [tree['entries'] for tree in record['trees'].values()]
        if len(counts) != 2 or len(set(counts)) != 1:
            record['errors'].append('tree entry counts do not match')
        record['bytes'] = os.stat(mini).st_size
    except (OSError, RuntimeError) as exc:
        record['errors'].append(str(exc))
    finally:
        if f:
            f.Close()
    record['passed'] = not record['errors']
    passed += record['passed']
    emit('sample', **record)
emit('summary', sampled=len(samples), passed=passed, failed=len(samples) - passed,
     elapsed_seconds=time.monotonic() - started,
     note='Stratified sample; not an exhaustive all-file integrity check')
if passed != len(samples) or not samples:
    raise SystemExit(1)
PY
